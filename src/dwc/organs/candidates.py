"""候选生成 —— EVOLUTION_CORE_V2 器官②（改什么）的**生成**那一半。

★★★ 为什么补这一段（"学习新规则"闭环的缺口）
  实测: evolver 此前只有 `Mutator.propose` —— 它**只查已有 RULES**
  ⇒⇒ ⇒★ 查不到 ⇒ 返回 None ⇒ diagnose 记 unmapped ⇒ **没有后续**
    ⇒⇒ ⇒★★ 于是整个系统**从失败里学不到任何新东西**:
      RULES 只有 3 条、全靠我手写 ⇒ 进化的"增量"至今没发生过
  ⇒⇒ ⇒★ 而这不是实现 bug —— 是**能力缺口**（见下）

★★★ 依据（两篇原文，一致）
  2606.14249 §3: "The action space ℰ is discrete but **open-ended**:
    each edit is a code-level artifact **generated by the meta-agent
    LLM**, not selected from a pre-enumerated set. Combinatorial
    explosion is managed ... by **the LLM's generative capacity** —
    the Planner proposes edits from **trace-grounded hypotheses**"
  2609.06396 Eq.10: `m`（可复用机制）由**模型假设**填
  ⇒⇒ ★★ 两篇一致 ⇒ 生成环节**需要模型**；而 DWC src 实测 grep
    零 LLM 接入 ⇒ 第一版只能是**确定性退化形态**

★★★★ 但"trace-grounded"这条线索允许确定性推导
  原文否定的是 "**pre-enumerated set**"（预枚举固定选项）
  而 trace-grounded = **基于本次失败证据**的推导
  ⇒⇒ ⇒★ 两者是对立概念:
     · 预枚举 `["A","B","C"]`（固定，与本次失败无关）= 违背原文
     · 由本次 `diffs` 推出的候选（换一批失败就换一批候选）= 符合
  ⇒⇒ ⇒★★ 所以本模块是**合法的确定性形态**，且显式标注 source

★★★ 三条纪律（与 JUDGE 的"缺证据不转正面判定"同型）
  ① 没有 diffs ⇒ **不产候选**（不许凭签名编）
  ② 每条候选必须带 `grounding`（引用具体哪条 diff）
  ③ 推不出 ⇒ 返回 `need_llm=True` + 原因（不许静默空返回）
    ⇒★ 空列表与"系统故障"必须可区分（原则 7/12）

定位声明（DWC-MEM · 判据 G1 定位门）
  ★ 本模块属记忆底座（进化侧），不判分（judge）、不落地（applier）
  ★ 它产出的是**候选**，去留由门与采纳判定决定
TRUTH_SOURCE = {
    "本模块不自判": "候选对不对由 judge 判 + Evolver.accept 采纳",
    "本模块的产出": "Candidate（patch + source + grounding），不是判分",
    "grounding 真值源": "dwc.organs.judge.Judge._diff 的逐条差异",
    "★ 降级标注": "source=deterministic ⇒ 2606.14249 的 LLM 形态未启用",
}
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple

class CandidateError(Exception):
    """违反候选生成契约（不许吞异常）。"""

@dataclass
class Candidate:
    """★ 一条候选 patch。★ 每条必须可归因到**具体 diff**。"""
    patch: str
    #: ★ source: deterministic(本模块推导) / llm(原文形态, 未启用)
    source: str
    #: ★★★ grounding: 依据哪条 diff —— 没有它就是"编造"
    grounding: List[Dict[str, Any]]
    #: 推导规则名（可审计: 哪条规则产的）
    rule: str = ""
    #: 供 Evolver.propose 的目标函数
    target: str = ""

    def __post_init__(self):
        if not self.grounding:
            raise CandidateError(
                "★ 纪律②: 候选必须带 grounding（依据哪条 diff）"
                " —— 无依据 = 编造，与「缺证据不转正面判定」同型")
        if self.source not in ("deterministic", "llm"):
            raise CandidateError("source=%r 不在允许值内" % self.source)
        if not self.patch.strip():
            raise CandidateError("候选 patch 不能为空")


class CandidateGenerator:
    """★ 候选生成器（V2 器官②的生成半边）。\n\n    ★★ 与 Mutator.propose 的分工:\n      propose  = **查表**（已知修复，RULES）\n      generate = **生成**（未知修复，本模块）\n      ⇒⇒ ⇒★ 于是闭环变成: 查表命中走 propose，\n        未命中**不再终止**，而是走 generate（学新的）\n    """

    #: ★★ G4 生灭门要求的**三件套**（母巢 L3: 1,447 生 / 5 死 的反面）
    #:   有生成 ⇒ 必须有淘汰(evict) · 有池 ⇒ 必须有上限(max_pool)
    #:   · 超限必须有行为(overflow) —— 三者皆由 G4 机械检查
    MAX_POOL = 8   # ★ G4 判据字面量: 池子上限

    def __init__(self, pool_limit: Optional[int] = None):
        self.rules_fired: List[str] = []
        #: ★★ 淘汰表: candidate_key → 被否决的原因（判分方写入）
        self.rejected: Dict[str, str] = {}
        self.pool_limit = (pool_limit if pool_limit is not None
                           else self.MAX_POOL)

    def key_of(self, c: "Candidate") -> str:
        """★ 候选身份（淘汰表用）—— patch + rule。"""
        return "%s|%s" % (c.rule, c.patch)

    def record_rejection(self, c: "Candidate", reason: str) -> None:
        """★★★ 判分方在**否决**某候选时必须调（G4 淘汰判据）。

        ★ 否则: 同一个错候选每轮都会被重新产出 ⇒ 空转
        ⇒⇒ 而"能生成但不淘汰"正是母巢 L3 的病
        """
        if not reason:
            raise CandidateError(
                "★ 淘汰必须给 reason（不许静默移除 —— 那会丢可审计性）")
        self.rejected[self.key_of(c)] = reason
        self.rules_fired.append("reject")

    # ── 纪律①/③ 的统一出口 ──
    @staticmethod
    def _empty(why: str, need_llm: bool) -> Dict[str, Any]:
        """★ 产不出时**显式**返回 —— 不许静默空列表。"""
        return {"candidates": [], "n": 0, "need_llm": need_llm,
                "why": why, "source": "none"}

    @staticmethod
    def _baseline_reproduces(bad: List[Dict[str, Any]],
                             src: str, fn_name: str) -> Optional[bool]:
        """★ 基线是否复现了 diffs 里的 actual（纪律④）。

        ★ 返回 None = **无法判定**（编译失败 / 无入参 / 非数值）
          ⇒ None **不当 False**（原则: 未评价不许当失败）
        ★ 返回 False = 明确不复现 ⇒ 必须拒绝该基线
        """
        fn = fn_name or (bad[0].get("fn") if bad else "")
        if not fn:
            return None
        ns: Dict[str, Any] = {}
        try:
            exec(compile(src, "<baseline>", "exec"), ns)
        except Exception:
            return None
        f = ns.get(fn)
        if not callable(f):
            return None
        checks = 0
        for d in bad:
            args, want = d.get("args"), d.get("actual")
            if not isinstance(args, (int, float)) or isinstance(args, bool):
                continue
            checks += 1
            try:
                got = f(args)
            except Exception:
                # ★ 基线跑出异常 ⇒ 它不产生 "actual" 那个值 ⇒ 不复现
                return False
            if got != want:
                return False
        return True if checks else None

    def generate(self, sig: Dict[str, str],
                 diffs: Optional[List[Dict[str, Any]]],
                 baseline_source: Optional[str],
                 fn_name: str = "") -> Dict[str, Any]:
        """★ 由失败证据生成候选 patch。\n\n        ★★ 输入的 diffs 必须来自 judge._diff（唯一真源）\n          ⇒ 若调用方手拼 diffs ⇒ grounding 会指向不存在的证据\n          ⇒⇒ 那是**编造**（由调用方负责，本模块无法识别）\n        """
        # ── 纪律①: 没有证据就不产 ──
        if not diffs:
            return self._empty(
                "★ 纪律①: 无 diffs ⇒ 不产候选"
                "（凭签名编 patch = 编造）", need_llm=False)
        bad = [d for d in diffs if not d.get("ok")]
        if not bad:
            return self._empty(
                "diffs 里没有失败条目 ⇒ 无候选可推", need_llm=False)
        if not baseline_source:
            return self._empty(
                "★ 缺 baseline_source ⇒ 无法在实现上施改"
                "（生成的是 patch，需要基线源码）", need_llm=True)

        # ★★★★ R31 新增纪律④: **基线必须能复现 diffs 的 actual**
        #   ★★ 实测: 我第一版传了 REFERENCE（**正确**的实现）当基线
        #     ⇒ 候选变成"对正确实现做扰动" ⇒ 必然越改越错
        #     ⇒⇒ ⇒★★ 而 grounding 里记的 expr 是 REFERENCE 的表达式
        #       = **grounding 指向了错误的证据**
        #   ⇒⇒ ⇒★ 这与纪律②同型（不许编造），只不过错的是**基线**
        #   ⇒ ⇒★ 该检查把"传对源码了吗"从**约定**变成**断言**
        repro = self._baseline_reproduces(bad, baseline_source, fn_name)
        if repro is False:
            return self._empty(
                "★ 纪律④: 基线无法复现 diffs 的 actual ⇒ 该 baseline_"
                "source **不是**产生这次失败的实现（我实测传过 "
                "REFERENCE 导致候选全错）", need_llm=False)

        cands: List[Candidate] = []
        fn = fn_name or bad[0].get("fn") or sig.get("fn", "")

        # ── 规则 R1: range 边界偏移（trace-grounded 于差值模式）──
        c1 = self._r1_range_offset(bad, baseline_source, fn)
        if c1:
            cands.extend(c1)
        # ── 规则 R2: 类型不匹配 ⇒ 字面量归一 ──
        c2 = self._r2_type_wrap(bad, baseline_source, fn)
        if c2:
            cands.extend(c2)

        # ★★★ G4 淘汰判据: 已被否决的候选**不再产出**（不许空转重试）
        before_reject = len(cands)
        cands = [c for c in cands
                 if self.key_of(c) not in self.rejected]
        n_rejected_skip = before_reject - len(cands)

        # ★★★ G4 池子上限 + 超限行为（不静默截断 —— 要报数）
        n_dropped = 0
        if len(cands) > self.pool_limit:
            # ★★ 超限行为: **截断**（保留排前的强假设）+ 显式报数
            n_dropped = len(cands) - self.pool_limit
            cands = cands[:self.pool_limit]

        if not cands:
            # ★ 但"全是已淘汰"与"推不出"是**不同的**原因，要分开报
            if n_rejected_skip:
                return {"candidates": [], "n": 0, "need_llm": False,
                        "source": "none",
                        "n_rejected_skipped": n_rejected_skip,
                        "why": ("★ G4 淘汰: 本轮候选**全部**已被否决"
                                "（%d 条）⇒ 不重试同一个错" % n_rejected_skip),
                        "rejected_pool": len(self.rejected)}
            # ── 纪律③: 推不出 ⇒ 显式 need_llm ──
            return self._empty(
                "★ 纪律③: 已有证据无法用确定性规则推导出 patch "
                "（c=%s q=%s）⇒ 需 2606.14249 的 LLM 形态" % (
                    sig.get("c"), sig.get("q")), need_llm=True)
        return {"candidates": cands, "n": len(cands),
                "need_llm": False,
                # ★ G4 的三个量都进返回（可机械检查）
                "pool_limit": self.pool_limit,
                "n_dropped": n_dropped,
                "n_rejected_skipped": n_rejected_skip,
                "n_rejected_pool": len(self.rejected),
                "why": "由 %d 条失败证据推导%s" % (
                    len(bad),
                    ("（超上限截断 %d 条）" % n_dropped) if n_dropped
                    else ""),
                "source": "deterministic",
                "★": ("★ source=deterministic ⇒ 2606.14249 的 LLM 形态"
                      "**未启用**（DWC 无 LLM 接入）")}

    # ── R1 · range 边界扰动（模式分类 + 局部扰动）──
    def _r1_range_offset(self, bad, src: str, fn: str) -> List[Candidate]:
        """★ 源码含 range 且差值与入参**相关** ⇒ 扰动边界产出候选。

        ★★★ R31 实测修正（我第一版规则是错的）:
          第一版要求 `len(set(deltas)) == 1`（差值恒定）才推
          而本例实测 Δ = 3 和 5 ⇒ **不恒定** ⇒ 第一版推不出
          ⇒⇒ ★★ 真实模式是 **Δ = args**（少算了 n 个）:
             n=3: range(3)=0+1+2=3 而期望 6 = 1+2+3
             n=5: range(5)=0..4=10  而期望 15 = 1..5
             ⇒⇒ ⇒★ 而正确修正是 `range(n+1)`
                （与已有 RULES 的 patch **完全一致**）
                ⇒ 说明证据**够**，是我的规则没覆盖这个模式
          ⇒⇒ ⇒★★ 而第一版的"加 delta"(delta=n) 会得 range(2n) ⇒ **错**
             根因: 我假设"差值恒定 ⇒ 加常数"，但此例修正**不是加常数**

        ★★★ 正确形态（2606.14249 "trace-grounded hypotheses"）:
          假设 = 推断 + **待验证** ⇒ 候选**不必一次推对**
          ⇒ 可对本次源码做**局部扰动**，交给**判分**去筛
          ⇒⇒ ★ 而"预枚举"被原文否定，是因为它与本次失败**无关**;
             此处只在**源码含 range 且差值与入参相关**时才扰动
             ⇒ 候选空间由**本次证据**决定 ⇒ 是 trace-grounded
        """
        pairs = []
        for d in bad:
            e, a = d.get("expected"), d.get("actual")
            if (isinstance(e, (int, float)) and isinstance(a, (int, float))
                    and not isinstance(e, bool) and not isinstance(a, bool)):
                pairs.append((d, e, a))
        # ★ 至少 2 条 —— 单条无法区分噪声与系统性偏移
        if len(pairs) < 2:
            return []
        deltas = [e - a for _, e, a in pairs]
        if all(x == 0 for x in deltas):
            return []
        # ★ 必须真的含 range(...) 才有可扰动的点
        m = re.search(r"range\(([^)]*)\)", src)
        if not m:
            return []
        arg = m.group(1)
        # ★★ 模式分类（决定扰动策略，也进 rule 名可审计）
        args_vals = [d.get("args") for d, _, _ in pairs]
        all_int_args = all(isinstance(x, int) and not isinstance(x, bool)
                           for x in args_vals)
        if all_int_args and all(da == g for da, g in zip(deltas, args_vals)):
            mode = "delta_eq_args"          # ★ 本例: Δ = args
        elif len(set(deltas)) == 1:
            mode = "delta_const"            # Δ 恒定
        else:
            mode = "delta_correlated"       # 有相关性但非上述
        # ★★★ 局部扰动集合（空间由本次源码的 range 表达式决定）
        forms: List[Tuple[str, str]] = []
        if "," in arg:
            a0, a1 = [x.strip() for x in arg.split(",", 1)]
            forms = [
                ("stop_plus1", "range(%s, %s + 1)" % (a0, a1)),
                ("stop_minus1", "range(%s, %s - 1)" % (a0, a1)),
                ("start_plus1", "range(%s + 1, %s)" % (a0, a1)),
            ]
        else:
            only = arg.strip()
            # ★★★ R31: **故意把最弱的放自然顺序首位**
            #   ⇒⇒ 否则"模式 B 排前"那条排序就是**死代码**
            #     （实测: 自然顺序本就 stop_plus1 第一 ⇒ 摘掉排序
            #       也一样 ⇒ 变异⑥抓不到 ⇒ 排序形同虚设）
            #   ⇒⇒ ⇒★ 而排序若永不受影响 = 幻影代码（名字对齐原则）
            #   ⇒ ⇒★ 现在弱假设先出现 ⇒ 排序必须**真的把它挪走**
            forms = [
                ("start1_weakest", "range(1, %s)" % only),
                ("stop_plus1", "range(%s + 1)" % only),
                ("stop_minus1", "range(%s - 1)" % only),
                ("start1_stop1", "range(1, %s + 1)" % only),
            ]
        # ★ 模式 B 的强假设优先排前（Δ=args ⇒ 少算了 args 个）
        if mode == "delta_eq_args":
            forms.sort(key=lambda kv: (0 if kv[0] in
                                       ("stop_plus1", "start1_stop1") else 1))
        out: List[Candidate] = []
        for where, expr in forms:
            new_src = src[:m.start()] + expr + src[m.end():]
            try:
                compile(new_src, "<cand>", "exec")
            except SyntaxError:
                continue        # ★ 编不过的不算候选（不产垃圾）
            out.append(Candidate(
                patch=self._body_of(new_src, fn),
                source="deterministic",
                rule="R1_%s_%s" % (mode, where),
                target=fn,
                grounding=[dict(d) for d, _, _ in pairs] + [{
                    "expr": m.group(0), "mode": mode,
                    "deltas": deltas, "args": args_vals,
                    "rule": ("扰动源码里的 %s；模式 %s"
                             "（Δ=%s · args=%s）"
                             % (m.group(0), mode, deltas, args_vals))}]))
        if out:
            self.rules_fired.append("R1:%s" % mode)
        return out

    # ── R2 · 类型不匹配 ──
    def _r2_type_wrap(self, bad, src: str, fn: str) -> List[Candidate]:
        """★ 期望数字实测字符串 ⇒ 候选: 在 return 处做字面量归一。"""
        hit = [d for d in bad
               if isinstance(d.get("expected"), (int, float))
               and isinstance(d.get("actual"), str)]
        if not hit:
            return []
        m = re.search(r"return\s+([^\n]+)", src)
        if not m:
            return []
        expr = m.group(1)
        forms = [
            ("int", "int(%s)" % expr),
            ("eval", "eval(%s)" % expr),
        ]
        out = []
        for kind, repl in forms:
            new_src = src[:m.start(1)] + repl + src[m.end(1):]
            out.append(Candidate(
                patch=self._body_of(new_src, fn),
                source="deterministic",
                rule="R2_wrap_%s" % kind,
                target=fn,
                grounding=[dict(d) for d in hit] +
                          [{"expr": m.group(0),
                            "rule": "期望 %s 型、实测 str"
                                    % type(hit[0]["expected"]).__name__}]))
        self.rules_fired.append("R2")
        return out

    @staticmethod
    def _body_of(src: str, fn: str) -> str:
        """★ 从完整源码取函数体（patch 的约定: 体的首行缩进 0）。"""
        lines = src.split("\n")
        if not lines or not lines[0].strip().startswith("def "):
            return src.strip()
        body = lines[1:]
        if not body:
            return "pass"
        # ★ 找最小非空缩进作为基准
        ind = min((len(b) - len(b.lstrip()) for b in body if b.strip()),
                  default=0)
        return "\n".join((b[ind:] if b.strip() else "") for b in body)
