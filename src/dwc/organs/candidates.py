class CandidateError(Exception):
    """违反候选生成契约（不许吞异常）。"""

@dataclass
class Candidate:
    """★ 一条候选 patch。★ 每条必须可归因到**具体 diff**。"""
    patch: str
    #: ★ source: deterministic(本模块推导) / llm(原文形态, 未启用)
    source: str
    #: ★★★ grounding: 依据哪条 diff —— 没有它就是"编造"
    grounding: List[Dict[str, Any]]
    #: 推导规则名（可审计: 哪条规则产的）
    rule: str = ""
    #: 供 Evolver.propose 的目标函数
    target: str = ""
    #: ★★★★ R37 · target_layer —— §四①「proposer 必须声明」的第 2 个字段
    #:   `component_type ∈ 𝒦 ⇒ target_layer 必为 assets`
    #:   `component_type ∈ 𝒦_meta ⇒ target_layer 必为 architecture`
    #:   ⇒⇒ ★★ 不一致 ⇒ **声明与意图矛盾，门应拒**（判据 K2）
    #:   ⇒ ⇒★ 为什么与 component **分别声明**（而不是推导一个就够）:
    #:     设计要的是"proposer 声明" ⇒ 让它**显式说出来**，
    #:     才能查出"说一套做一套"（§四① 的原话是『必须声明』两个字段）
    target_layer: str = ""
    #: ★★★ R34 · m = **机制假设**（EVOLUTION_CORE_DESIGN §9 第 4 项:
    #:   「m 由**模型**填」· 2609.06396 Eq.10 同）
    #:   ★★ 为什么以前没有这个字段:
    #:     确定性形态的 m 从 **RULES 条目**读（rule.get("m")）
    #:     ⇒ 生成器**不需要**带它 ⇒ 字段不存在
    #:   ⇒ ⇒★ 而 LLM 形态产的候选**本来就没有 RULES 条目**
    #:     ⇒⇒ 没有 m 字段就没地方放「模型假设的机制」
    #:     ⇒⇒ ⇒★★ 于是 **2609.06396 的 m 分工在代码里落不了地**
    #:   ⇒ ⇒★ 所以这是补**设计缺口**，不是顺手加字段
    m: str = ""
    #: ★ m 的来源（诚实标注: 是规则读来的还是模型假设的）
    m_source: str = "none"   # rule / llm / none
    #: ★★★ R35 · component / dimension —— **谁来填**?
    #:   按 RRSI 式12/15: 𝒦(9) 词表 + 九维是**契约**（受约束的选）
    #:   ⇒ 确定性形态: 从 RULES 条目读（现成的）
    #:   ⇒ LLM 形态: **让模型在词表内选**（prompt 给全词表 + 定义）
    #:   ⇒⇒ ★★ 绝不自己瞎填 —— 那是编造（与纪律①同型）
    #:     实测: 我 R32 固化时**手填**了 control_flow/D7，
    #:     那次我有规则可依；这次是**无规则**场景 ⇒ 必须由证据产
    component: str = ""
    dimension: str = ""
    #: ★★★ m 的**调用指纹**（R35: m 由模型产 ⇒ 两次措辞不同）
    #:   ⇒ 若固化只记 m 本身 ⇒ 后人无法回溯"这条 m 哪次调用来的"
    #:   ⇒ ⇒★ 记指纹 (model, n_diffs, prompt_ver, ts) ⇒ 可审计且
    #:     **不假装 m 可复现**（温度 0.2 也不保证逐字一致）
    provenance: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        if not self.grounding:
            raise CandidateError(
                "★ 纪律②: 候选必须带 grounding（依据哪条 diff）"
                " —— 无依据 = 编造，与「缺证据不转正面判定」同型")
        if self.source not in ("deterministic", "llm"):
            raise CandidateError("source=%r 不在允许值内" % self.source)
        if not self.patch.strip():
            raise CandidateError("候选 patch 不能为空")


class CandidateGenerator:
    """★ 候选生成器（V2 器官②的生成半边）。\n\n    ★★ 与 Mutator.propose 的分工:\n      propose  = **查表**（已知修复，RULES）\n      generate = **生成**（未知修复，本模块）\n      ⇒⇒ ⇒★ 于是闭环变成: 查表命中走 propose，\n        未命中**不再终止**，而是走 generate（学新的）\n    """

    #: ★★ G4 生灭门要求的**三件套**（母巢 L3: 1,447 生 / 5 死 的反面）
    #:   有生成 ⇒ 必须有淘汰(evict) · 有池 ⇒ 必须有上限(max_pool)
    #:   · 超限必须有行为(overflow) —— 三者皆由 G4 机械检查
    MAX_POOL = 8   # ★ G4 判据字面量: 池子上限

    def __init__(self, pool_limit: Optional[int] = None,
                 llm: Optional[Any] = None):
        self.rules_fired: List[str] = []
        #: ★★★ R34 · LLM 形态（可选 —— 不给 = 保持确定性退化形态）
        #:   ★ 为什么默认不自动建 client:
        #:     建 client 会读环境变量 ⇒ 若有人误配了错误端点，
        #:     每次推不出都会**发网络请求**（时间+配额）
        #:     ⇒ 对"降级"这个**常态路径**是无谓开销
        #:   ⇒ ⇒★ 所以由调用方显式注入（e2e / 测试各自主动选择）
        self.llm = llm
        #: ★★ LLM 调用账本（可审计: 走没走 LLM、成没成）
        self.n_llm_calls = 0
        self.n_llm_ok = 0
        #: ★★ 淘汰表: candidate_key → 被否决的原因（判分方写入）
        self.rejected: Dict[str, str] = {}
        self.pool_limit = (pool_limit if pool_limit is not None
                           else self.MAX_POOL)
        #: ★★★ R32 · 静默跳过的**痕迹**（G7 的盲区在补）
        #:   ⇒ 编不过的候选仍不产出（不产垃圾），但**必须可审计**
        self.n_syntax_rejected = 0
        self.syntax_rejects: List[Dict[str, Any]] = []

    def key_of(self, c: "Candidate") -> str:
        """★ 候选身份（淘汰表用）—— patch + rule。"""
        return "%s|%s" % (c.rule, c.patch)

    def record_rejection(self, c: "Candidate", reason: str) -> None:
        """★★★ 判分方在**否决**某候选时必须调（G4 淘汰判据）。

        ★ 否则: 同一个错候选每轮都会被重新产出 ⇒ 空转
        ⇒⇒ 而"能生成但不淘汰"正是母巢 L3 的病
        """
        if not reason:
            raise CandidateError(
                "★ 淘汰必须给 reason（不许静默移除 —— 那会丢可审计性）")
        self.rejected[self.key_of(c)] = reason
        self.rules_fired.append("reject")

    # ── 纪律①/③ 的统一出口 ──
    @staticmethod
    def _empty(why: str, need_llm: bool) -> Dict[str, Any]:
        """★ 产不出时**显式**返回 —— 不许静默空列表。"""
        return {"candidates": [], "n": 0, "need_llm": need_llm,
                "why": why, "source": "none"}

    @staticmethod
    def _baseline_reproduces(bad: List[Dict[str, Any]],
                             src: str, fn_name: str) -> Optional[bool]:
        """★ 基线是否复现了 diffs 里的 actual（纪律④）。

        ★ 返回 None = **无法判定**（编译失败 / 无入参 / 非数值）
          ⇒ None **不当 False**（原则: 未评价不许当失败）
        ★ 返回 False = 明确不复现 ⇒ 必须拒绝该基线
        """
        fn = fn_name or (bad[0].get("fn") if bad else "")
        if not fn:
            return None
        ns: Dict[str, Any] = {}
        try:
            exec(compile(src, "<baseline>", "exec"), ns)
        except Exception:
            return None
        f = ns.get(fn)
        if not callable(f):
            return None
        checks = 0
        for d in bad:
            args, want = d.get("args"), d.get("actual")
            if not isinstance(args, (int, float)) or isinstance(args, bool):
                continue
            checks += 1
            try:
                got = f(args)
            except Exception:
                # ★ 基线跑出异常 ⇒ 它不产生 "actual" 那个值 ⇒ 不复现
                return False
            if got != want:
                return False
        return True if checks else None

    def generate(self, sig: Dict[str, str],
                 diffs: Optional[List[Dict[str, Any]]],
                 baseline_source: Optional[str],
                 fn_name: str = "") -> Dict[str, Any]:
        """★ 由失败证据生成候选 patch。\n\n        ★★ 输入的 diffs 必须来自 judge._diff（唯一真源）\n          ⇒ 若调用方手拼 diffs ⇒ grounding 会指向不存在的证据\n          ⇒⇒ 那是**编造**（由调用方负责，本模块无法识别）\n        """
        # ── 纪律①: 没有证据就不产 ──
        if not diffs:
            return self._empty(
                "★ 纪律①: 无 diffs ⇒ 不产候选"
                "（凭签名编 patch = 编造）", need_llm=False)
        bad = [d for d in diffs if not d.get("ok")]
        if not bad:
            return self._empty(
                "diffs 里没有失败条目 ⇒ 无候选可推", need_llm=False)
        if not baseline_source:
            return self._empty(
                "★ 缺 baseline_source ⇒ 无法在实现上施改"
                "（生成的是 patch，需要基线源码）", need_llm=True)

        # ★★★★ R31 新增纪律④: **基线必须能复现 diffs 的 actual**
        #   ★★ 实测: 我第一版传了 REFERENCE（**正确**的实现）当基线
        #     ⇒ 候选变成"对正确实现做扰动" ⇒ 必然越改越错
        #     ⇒⇒ ⇒★★ 而 grounding 里记的 expr 是 REFERENCE 的表达式
        #       = **grounding 指向了错误的证据**
        #   ⇒⇒ ⇒★ 这与纪律②同型（不许编造），只不过错的是**基线**
        #   ⇒ ⇒★ 该检查把"传对源码了吗"从**约定**变成**断言**
        repro = self._baseline_reproduces(bad, baseline_source, fn_name)
        if repro is False:
            return self._empty(
                "★ 纪律④: 基线无法复现 diffs 的 actual ⇒ 该 baseline_"
                "source **不是**产生这次失败的实现（我实测传过 "
                "REFERENCE 导致候选全错）", need_llm=False)

        cands: List[Candidate] = []
        fn = fn_name or bad[0].get("fn") or sig.get("fn", "")

        # ── 规则 R1: range 边界偏移（trace-grounded 于差值模式）──
        c1 = self._r1_range_offset(bad, baseline_source, fn)
        if c1:
            cands.extend(c1)
        # ── 规则 R2: 类型不匹配 ⇒ 字面量归一 ──
        c2 = self._r2_type_wrap(bad, baseline_source, fn)
        if c2:
            cands.extend(c2)

        # ★★★ G4 淘汰判据: 已被否决的候选**不再产出**（不许空转重试）
        before_reject = len(cands)
        cands = [c for c in cands
                 if self.key_of(c) not in self.rejected]

        # ★★★ R37 · 统一 target_layer（同上，防漏）
        #   ⇒ component 在 ⇒ 由 `layer_of` 推（§四① 真值表）
        #   ⇒ 无 component（R2 那类无依据的）⇒ 保持空 ⇒ K2 拒
        for _c in cands:
            if not getattr(_c, "target_layer", "") and getattr(
                    _c, "component", ""):
                _c.target_layer = layer_of(_c.component)

        # ★★★ R35 · 统一 target（**防"加字段没同步构造"再发生**）
        #   ⇒ 我 R35 加了 component/dimension/provenance，却漏了 target
        #     ⇒ 于是固定化流水线**断在 schema**（check_entry 报缺 target）
        #   ⇒⇒ ⇒★★ 这类错我已犯多次 ⇒ 与其逐个补，不如**在此统一收口**:
        #     缺 target 的候选一律从 fn 推（fn 是 generate 的入参，必有）
        for _c in cands:
            if not getattr(_c, "target", ""):
                _c.target = fn
        assert all(getattr(_c, "target", "") for _c in cands), \
            "★ 统一 target 失败（不该走到这）"
        n_rejected_skip = before_reject - len(cands)

        # ★★★ G4 池子上限 + 超限行为（不静默截断 —— 要报数）
        n_dropped = 0
        if len(cands) > self.pool_limit:
            # ★★ 超限行为: **截断**（保留排前的强假设）+ 显式报数
            n_dropped = len(cands) - self.pool_limit
            cands = cands[:self.pool_limit]

        if not cands:
            # ★ 但"全是已淘汰"与"推不出"是**不同的**原因，要分开报
            if n_rejected_skip:
                return {"candidates": [], "n": 0, "need_llm": False,
                        "source": "none",
                        "n_rejected_skipped": n_rejected_skip,
                        "why": ("★ G4 淘汰: 本轮候选**全部**已被否决"
                                "（%d 条）⇒ 不重试同一个错" % n_rejected_skip),
                        "rejected_pool": len(self.rejected)}
            # ── 纪律③ · R34: 有 LLM ⇒ 转它；没有 ⇒ 显式 need_llm ──
            #   ★★ 这是 `need_llm` 从「只报」变「能跑」的位置
            if self.llm is not None:
                r = self._llm_generate(sig, diffs, baseline_source, fn)
                if r["ok"]:
                    # ★ LLM 给了候选 ⇒ 仍过**同样的**池上限/淘汰
                    cands = list(r["candidates"])
                    skipped = [c for c in cands
                               if self.key_of(c) in self.rejected]
                    cands = [c for c in cands
                             if self.key_of(c) not in self.rejected]
                    dropped = 0
                    if len(cands) > self.pool_limit:
                        dropped = len(cands) - self.pool_limit
                        cands = cands[:self.pool_limit]
                    if cands:
                        return {"candidates": cands, "n": len(cands),
                                "need_llm": False, "source": "llm",
                                "pool_limit": self.pool_limit,
                                "n_dropped": dropped,
                                "n_rejected_skipped": len(skipped),
                                "n_rejected_pool": len(self.rejected),
                                "m_hint": r.get("m_hint", ""),
                                "n_syntax_rejected": self.n_syntax_rejected,
                                "why": ("★ R34 LLM 形态产出 %d 条%s"
                                        "（2606.14249 §3 形态）"
                                        % (len(cands),
                                           ("，超上限截断 %d" % dropped)
                                           if dropped else ""))}
                    cause = r.get("cause") or "LLM 候选全被池过滤"
                else:
                    cause = r.get("cause") or "LLM 未产出"
                # ★ 仍 need_llm=True，但**带上 LLM 的真实原因**
                #   （否则"没接 LLM"与"接了但失败"不可区分 = 静默）
                return self._empty(
                    "★★ 确定性推不出 + LLM 形态也未产出"
                    "（source=%s，cause=%s）"
                    % (r.get("source"), str(cause)[:80]),
                    need_llm=True)
            # ── 无 LLM 注入（保持退化形态，如实报）──
            return self._empty(
                "★ 纪律③: 已有证据无法用确定性规则推导出 patch "
                "（c=%s q=%s）⇒ 需 2606.14249 的 LLM 形态（本进程未注入）"
                % (sig.get("c"), sig.get("q")),
                need_llm=True)
        return {"candidates": cands, "n": len(cands),
                "need_llm": False,
                # ★ G4 的三个量都进返回（可机械检查）
                "pool_limit": self.pool_limit,
                "n_dropped": n_dropped,
                "n_rejected_skipped": n_rejected_skip,
                "n_rejected_pool": len(self.rejected),
                "why": "由 %d 条失败证据推导%s" % (
                    len(bad),
                    ("（超上限截断 %d 条）" % n_dropped) if n_dropped
                    else ""),
                "source": "deterministic",
                "★": ("★ source=deterministic ⇒ 2606.14249 的 LLM 形态"
                      "**未启用**（DWC 无 LLM 接入）")}

    # ══════════════════════════════════════════════════════
    # ★★★★ R34 · LLM 形态（填 `need_llm` 的缺口）
    #   ★ 依据（两篇一致）:
    #     2606.14249 §3: 候选『generated by the meta-agent LLM,
    #       not selected from a pre-enumerated set』
    #     2609.06396 Eq.10: m 由**模型假设**填
    #   ⇒ ⇒★ 而确定性形态只覆盖『源码含 range 且差值与入参相关』
    #     ⇒ LLM 形态补上其余（尤其 m 的假设）
    #
    # ★★ 写法约束（R34 实测踩坑后立的）:
    #   本段经**嵌套三引号**写入 ⇒ 任何 "\n" 字面量都会被外层吃掉
    #   真换行 ⇒ 文件语法直接坏（第一次写就坏在这里）
    #   ⇒ ⇒★ 一律 `splitlines()` + `chr(10)`，全程不出现 \n 字面量
    # ══════════════════════════════════════════════════════

    #: ★ 纪律④⑤ 对 LLM 候选**同样生效**（不是"模型说的就信"）
    LLM_MAX_CANDIDATES = 4
    #: ★★ prompt 版本号 —— 进 m 的指纹（换 prompt ⇒ 指纹变 ⇒ 可审计）
