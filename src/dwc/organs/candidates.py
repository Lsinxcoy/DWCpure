            #   实测: 我把它放在前文的三行说明里，模型仍给了
            #   `component='code'`(𝒦_meta) + `target_layer='assets'`
            #   ⇒ K2 正确拒了 ⇒ 但 e2e 因此跑不通
            #   ⇒⇒ ⇒★ 教训: 约束放**离输出格式最近**的地方
            #     （模型对格式行的关注度最高 —— 前文说明容易被忽略）
            #   ⇒ ⇒★ 且把映射**写进占位符**（不另起说明行）
