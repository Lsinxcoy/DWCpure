"""DWC 的 LLM 接入层。

═══════════════════════════════════════════════════════════
定位声明 · **DWC-AUTO**（自我强化）
  ★ 本层**当前唯一用途** = `organs/candidates.py` 的 LLM 形态
    （2606.14249 §3 / 2609.06396 Eq.10: 候选与 m 由模型生成）
    ⇒ 那是**进化环**的一段 ⇒ 归自我强化
  ★★ 为什么不是 DWC-MEM: 它不存任何记忆、不参与记忆读写
    （`candidates.py` 标 DWC-MEM 是因为**它自己**落在记忆底座）
  ★★★ 若未来 `judge` 的 L2 语义层也用本层（那是**判分**），
    则必须**重新定位**或拆分 —— 因为 G1 的语义是"服务哪件事"
    ⇒ 一件模块同时服务两件事 = 抢位（G1 要查的正是这个）
    ⇒ ⇒★ 现在不抢，写在这里让后来者看得见
═══════════════════════════════════════════════════════════

★★★★ 为什么这一层必须存在（R34 · 实测起因）
  R31 实测: `src/` **零 LLM 接入** ⇒ 候选生成只能是**确定性退化形态**
  ⇒ 而两篇原文一致指明候选**该由模型生成**:
     · 2606.14249 §3: 候选『generated by the meta-agent LLM,
       not selected from a pre-enumerated set』from『trace-grounded
       hypotheses』
     · 2609.06396 Eq.10: m（机制假设）由**模型**填
  ⇒⇒ ⇒★ 于是 `candidates.generate()` 推不出时只能报 `need_llm=True`
    —— 那是**只报不跑**，缺口就在这一层
  ⇒ ⇒★ 补上它，`need_llm` 才从"报告缺口"变成"填上缺口"

★★ 设计对齐（ARCHITECTURE §4.2 守卫① 定稿 · 不是 ARSI 那套）
  ```text
  if conf_gate.accuracy >= theta_dev:
      decision = world_model.predict(state)
  else:
      decision = llm_governor.decide(state)
      if llm_unavailable: decision = heuristic(state)   # ★ 降级必留痕
  ```
  ★ 被否的是 ARSI 的 `confidence > 0.1`（该值由**被门控者自己**写出，
    是"见过几次/20"的**计数器**；且 ARSI 自陈 holdout 0.94 实盘 0）
  ★⇒ 本模块**不做门控**（那是 llm_governor / judge 的职责），
    只做一件事: **把一次调用成功/失败如实报回来**

═══════════════════════════════════════════════════════════
 本模块的三条纪律（缺一则退化）
   ① 凭证**绝不外流**: 不进 repr / str / 日志 / 异常消息
      —— 任何一处泄漏 = 密钥泄露（且是**静默**的泄露）
   ② 失败**不抛也不吞**: 返回 `LLMResult(ok=False, error=...)`
      —— 抛会让调用方 try/except 里 `pass`（G7 同款）；
        吞会让"降级"与"成功"不可区分
   ③ `configured` 与 `available` **分开**:
      configured = 有配置（静态）· available = 配置且实测可达（动态）
      ⇒ 否则"配了但不通"会被读成"能用"
═══════════════════════════════════════════════════════════
"""
from __future__ import annotations
import io

import json
import os
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from typing import Any, Dict, Optional

#: ★ 配置来源（优先级从高到低）: 环境变量 → config/llm.json
#:   ★★ 为什么不去读宿主（Hermes）的配置:
#     ① 那是**别的系统的凭证**，越权取用不是"复用"
#     ② 设计已定 DWC「独立 agent, 自带 LLM 调用, 走云端 API」
#       ⇒ 凭证来源也应是**它自己的**（可配置、可审计）
ENV_BASE = "DWC_LLM_BASE_URL"
ENV_KEY = "DWC_LLM_API_KEY"
ENV_MODEL = "DWC_LLM_MODEL"
ENV_TIMEOUT = "DWC_LLM_TIMEOUT"


def _load_file_config() -> Dict[str, str]:
    """★ 读 `config/llm.json`（docstring 承诺的第二配置源）。

    ★★★ R34 实测: 我第一版 **docstring 写了它、实现没写**
      ⇒⇒ 那正是「名字与实现不对齐」（原则 12 的反面）
        ⇒⇒ 而我 R34 刚立过"幻影代码"的规矩，转头又犯同型
    ⇒ ⇒★ 现在补上: 优先级 **环境变量 > 配置文件**
      （环境变量给 CI/临时用；文件给长期配）

    ★★ 文件含**凭证** ⇒ 必须已被 .gitignore 排除（R34 已加）
      否则 key 进 git 历史洗不掉（母巢 HIVE_TOKEN 同款教训）

    文件不存在/坏掉 ⇒ 返回 {}（**不报错** —— 没配是常态）
    """
    path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(
            os.path.dirname(os.path.abspath(__file__))))),
        "config", "llm.json")
    try:
        with io.open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict):
        return {}
    # ★ 白名单取键（多余键不认 —— 避免把别的东西当配置）
    return {k: str(data[k]).strip()
            for k in ("base_url", "api_key", "model", "timeout")
            if str(data.get(k, "")).strip()}


@dataclass
class LLMResult:
    """★ 一次调用的**如实**结果（成功与失败同构，便于记录与降级）。

    ★★★ `source` 是给**因果链**读的（ARCHITECTURE: 每次决策要能回答
      "是谁说的"）—— 所以它必须永远被填上，不能是空。
    """
    ok: bool = False
    text: str = ""
    source: str = "unavailable"   # llm / unavailable / error / not_configured
    error: str = ""
    #: ★★ 凭证相关的字段**一律不出现**（纪律①）
    meta: Dict[str, Any] = field(default_factory=dict)

    @property
    def degraded(self) -> bool:
        """★ 是否降级（供调用方走 heuristic 分支）。"""
        return not self.ok

    def __str__(self) -> str:
        # ★★★ 纪律①: 即便有人直接打印，也**拿不到**任何配置值
        return ("LLMResult(ok=%r, source=%r, text_len=%d, error=%r)"
                % (self.ok, self.source, len(self.text), self.error[:120]))


class LLMClient:
    """★ 一次 LLM 调用的最小客户端（**零第三方依赖**，走 urllib）。

    ★★★ 为什么不引 requests/httpx:
      实测 `src/` 零网络调用、仓库**无任何依赖声明**
      ⇒ 为一个分支引入第三方依赖 = 改变项目的依赖前提
      （那是**先想清楚**而非顺手做的决定）
    """

    def __init__(self, base_url: Optional[str] = None,
                 api_key: Optional[str] = None,
                 model: Optional[str] = None,
                 timeout: float = 30.0,
                 probe: bool = False):
        # ★ 优先级: 显式参数 > 环境变量 > config/llm.json（docstring 承诺）
        _fc = _load_file_config()
        self._base = (base_url or os.environ.get(ENV_BASE, "")
                      or _fc.get("base_url", "")).strip()
        self._key = (api_key if api_key is not None
                     else (os.environ.get(ENV_KEY, "")
                           or _fc.get("api_key", ""))).strip()
        self._model = (model or os.environ.get(ENV_MODEL, "")
                       or _fc.get("model", "")).strip()
        try:
            self.timeout = float(os.environ.get(ENV_TIMEOUT, "")
                                 or _fc.get("timeout", "") or timeout)
        except ValueError:
            self.timeout = float(timeout)
        #: ★★ 三态分开（纪律③）: configured 是**静态**的
        self.configured = bool(self._base and self._key and self._model)
        self._probe = probe
        #: 调用账本（可审计: 试了几次、成几次）
        self.n_calls = 0
        self.n_ok = 0
        self.n_fail = 0

    # ── 凭证护栏（纪律①）─────────────────────────────────

    def __repr__(self) -> str:
        return ("LLMClient(configured=%s, model=%r, timeout=%s, base_host=%r)"
                % (self.configured, self._model, self.timeout,
                   self._host_only()))

    def _host_only(self) -> str:
        """★ 只留 host（端口不含路径）—— 便于排查且**不含 key**。"""
        try:
            from urllib.parse import urlparse
            return urlparse(self._base).netloc or ""
        except Exception:
            return ""

    def __getstate__(self) -> Dict[str, Any]:
        """★ 序列化时**丢掉 key**（否则可能被写进中间产物/缓存）。"""
        st = self.__dict__.copy()
        st["_key"] = ""
        return st

    # ── 可用性（三态）──────────────────────────────────

    @property
    def unavailable_reason(self) -> str:
        """★ 静态不可用的原因（**永远非空** —— 不许返回空字符串）。"""
        if not self._base:
            return ("未配置 %s，也未在 config/llm.json 给 base_url"
                    % ENV_BASE)
        if not self._key:
            return "未配置 %s" % ENV_KEY
        if not self._model:
            return "未配置 %s" % ENV_MODEL
        return ""

    def probe(self) -> LLMResult:
        """★ 动态探活（可选 —— 默认不发网络请求）。

        ★★ 为什么不默认探: 探活本身要花一次调用（时间+配额）
          ⇒ 若每个用到的地方都探，成本会**乘上去**
          ⇒ ⇒★ 交给调用方在需要时显式调
        """
        if not self.configured:
            return LLMResult(ok=False, source="not_configured",
                             error=self.unavailable_reason or "无配置")
        return self.complete("ping", max_tokens=8)

    # ── 调用 ──────────────────────────────────────────

    def complete(self, prompt: str, *, system: Optional[str] = None,
                 max_tokens: int = 1200, json_mode: bool = False
                 ) -> LLMResult:
        """★ 一次补全。**不抛异常**（纪律②），失败也带 `error` 返回。

        ★★★ 为什么不用异常: 调用方最常见的写法是
          `try: llm.complete(...) except: pass`
          ⇒⇒ 那正是 G7 静默门要防的（我 R29 刚因此被抓过）
        ⇒ ⇒★ 返回值模式让"降级"成为**正常分支**而非异常分支
        """
        if not self.configured:
            return LLMResult(ok=False, source="not_configured",
                             error=self.unavailable_reason or "无配置")

        body: Dict[str, Any] = {
            "model": self._model,
            "messages": ([{"role": "system", "content": system}]
                         if system else [])
            + [{"role": "user", "content": prompt}],
            "max_tokens": max_tokens,
            "temperature": 0.2,   # ★ 低温度: 候选要可复现（便于判分）
        }
        if json_mode:
            body["response_format"] = {"type": "json_object"}

        self.n_calls += 1
        url = self._base.rstrip("/") + "/chat/completions"
        req = urllib.request.Request(
            url, data=json.dumps(body).encode("utf-8"),
            headers={
                "Content-Type": "application/json",
                # ★★★ 纪律①: key 只出现在这一处请求头里，
                #   不落日志、不进异常、不进 repr
                "Authorization": "Bearer " + self._key,
            },
            method="POST")
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                raw = resp.read().decode("utf-8", "replace")
        except urllib.error.HTTPError as e:
            self.n_fail += 1
            # ★★ 只读 e.code/e.reason —— 不要读 body（可能回显你的请求，
            #   含 Authorization ⇒ 会把 key 带进 error 字符串）
            return LLMResult(ok=False, source="error",
                             error="HTTP %s: %s" % (e.code, e.reason),
                             meta={"http_code": e.code})
        except Exception as e:      # ★ 网络/超时/解析 —— 统一收敛
            self.n_fail += 1
            return LLMResult(ok=False, source="error",
                             error="%s: %s" % (type(e).__name__, e),
                             meta={"kind": "transport"})
        try:
            data = json.loads(raw)
            text = data["choices"][0]["message"]["content"]
        except Exception as e:
            self.n_fail += 1
            return LLMResult(ok=False, source="error",
                             error="响应解析失败: %s" % e,
                             meta={"kind": "parse"})
        if not isinstance(text, str) or not text.strip():
            self.n_fail += 1
            return LLMResult(ok=False, source="error",
                             error="返回内容为空（不许静默当成功）",
                             meta={"kind": "empty"})
        self.n_ok += 1
        return LLMResult(ok=True, text=text, source="llm",
                         meta={"model": self._model,   # ★ model 名可记
                               "n_chars": len(text)})

    def stats(self) -> Dict[str, Any]:
        """★ 调用账本（不含量任何凭证）。"""
        return {"configured": self.configured, "model": self._model,
                "n_calls": self.n_calls, "n_ok": self.n_ok,
                "n_fail": self.n_fail,
                "★": "凭证不在此处任何字段里（纪律①）"}
