#: ★★★ R379 · 模块级 HTTP 串行锁。
#:   现场取证（2026-10-20 对照实验）: 同一端点、同一 prompt、同一配置，
#:     · 串行 4 个任务 ⇒ 4/4 返回 JSON
#:     · 并发 4 线程  ⇒ 0/4 返回 JSON（含 finish=tool_calls、content 空、
#:       自然语言散文）
#:     · 并发 + 各自独立 session ⇒ 仍 0/4
#:     · 并发 + 全局锁串行化     ⇒ 4/4
#:   ⇒ 端点**并发下不遵守 `response_format: json_object`**。而 DWC 的
#:     `Semaphore(2)` 允许 2 单并发（收件箱异步接单）⇒ 生产必踩。
#:   确定性控制用代码（不是靠 prompt 求模型）：请求串行化，模型侧行为恢复。
#:   必须**模块级**（生产每单新建 `LLMClient()`，实例锁挡不住跨实例并发）。
#:
#: ★★★ R435 · 换端点后重新验证（2026-10-22，当前 mcgrox + deepseek-v4.1-flash）:
#:     串行 12 次 ⇒ 12/12 合法 JSON，33.1s
#:     并发 4 路 12 次 ⇒ **12/12 合法 JSON**，7.9s（4.17×）
#:   ⇒ 旧结论只对旧端点成立。宽度改由 `DWC_HTTP_CONCURRENCY` 控制，
#:     **默认 1（保持历史行为）**；只有 A/B 这种"要速度"的场景显式调高。
#:     上限 8：再高对端点不礼貌，且收益递减。
def _http_width() -> int:
    import os as _os
    raw = (_os.environ.get("DWC_HTTP_CONCURRENCY") or "1").strip()
    try:
        n = int(raw)
    except ValueError:
        n = 1
    return max(1, min(8, n))


_HTTP_WIDTH = _http_width()
_HTTP_LOCK = threading.Semaphore(_HTTP_WIDTH)


def _load_file_config() -> Dict[str, str]:
    """★ 读 `config/llm.json`（docstring 承诺的第二配置源）。

    ★★★ R34 实测: 我第一版 **docstring 写了它、实现没写**
      ⇒⇒ 那正是「名字与实现不对齐」（原则 12 的反面）
        ⇒⇒ 而我 R34 刚立过"幻影代码"的规矩，转头又犯同型
    ⇒ ⇒★ 现在补上: 优先级 **环境变量 > 配置文件**
      （环境变量给 CI/临时用；文件给长期配）

    ★★ 文件含**凭证** ⇒ 必须已被 .gitignore 排除（R34 已加）
      否则 key 进 git 历史洗不掉（母巢 HIVE_TOKEN 同款教训）

    文件不存在/坏掉 ⇒ 返回 {}（**不报错** —— 没配是常态）
    """
    path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(
            os.path.dirname(os.path.abspath(__file__))))),
        "config", "llm.json")
    try:
        with io.open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict):
        return {}
    # ★ 白名单取键（多余键不认 —— 避免把别的东西当配置）
    # ★★★ R377 · 白名单必须包含新增键，否则**静默丢弃**（本次事故：
    #   config 里写了 max_tokens/reasoning_effort 却完全不生效，排障时
    #   看到的是「配了没用」而不是「没配」—— 最坏的一种静默）。
    _KEYS = ("base_url", "api_key", "model", "timeout",
             "max_tokens", "reasoning_effort")
    return {k: str(data[k]).strip()
            for k in _KEYS
            if str(data.get(k, "")).strip()}


@dataclass
class LLMResult:
    """★ 一次调用的**如实**结果（成功与失败同构，便于记录与降级）。

    ★★★ `source` 是给**因果链**读的（ARCHITECTURE: 每次决策要能回答
      "是谁说的"）—— 所以它必须永远被填上，不能是空。
    """
    ok: bool = False
    text: str = ""
    source: str = "unavailable"   # llm / unavailable / error / not_configured
    error: str = ""
    #: ★★ 凭证相关的字段**一律不出现**（纪律①）
    meta: Dict[str, Any] = field(default_factory=dict)

    @property
    def degraded(self) -> bool:
        """★ 是否降级（供调用方走 heuristic 分支）。"""
        return not self.ok

    def __str__(self) -> str:
        # ★★★ 纪律①: 即便有人直接打印，也**拿不到**任何配置值
        return ("LLMResult(ok=%r, source=%r, text_len=%d, error=%r)"
                % (self.ok, self.source, len(self.text), self.error[:120]))


class LLMClient:
    """★ 一次 LLM 调用的最小客户端（**零第三方依赖**，走 urllib）。

    ★★★ 为什么不引 requests/httpx:
      实测 `src/` 零网络调用、仓库**无任何依赖声明**
      ⇒ 为一个分支引入第三方依赖 = 改变项目的依赖前提
      （那是**先想清楚**而非顺手做的决定）
    """

    def __init__(self, base_url: Optional[str] = None,
                 api_key: Optional[str] = None,
                 model: Optional[str] = None,
                 timeout: Optional[float] = None,
                 probe: bool = False,
                 max_tokens: Optional[int] = None,
                 reasoning_effort: Optional[str] = None):
        # ★★★ R36: timeout 默认必须是 **None**（不是 30.0）
        #   否则"不传参数"= 传了 30 ⇒ env/config 文件永远被盖住
        #   ⇒⇒ 而 docstring 说「参数 > env > 文件」⇒ 又一处不对齐
        # ★ 优先级: 显式参数 > 环境变量 > config/llm.json（docstring 承诺）
        _fc = _load_file_config()
        #: ★ R308-③ · 每配置项的来源层（只记层名不记值：explicit/env/file/factory）。
        #:   追加记账，不动上面三行的解决口径。
        _src: Dict[str, str] = {}
        if base_url:
            _src["base_url"] = "explicit"
        elif os.environ.get(ENV_BASE, ""):
            _src["base_url"] = "env"
        elif _fc.get("base_url", ""):
            _src["base_url"] = "file"
        if api_key is not None:
            _src["api_key"] = "explicit"
        elif os.environ.get(ENV_KEY, ""):
            _src["api_key"] = "env"
        elif _fc.get("api_key", ""):
            _src["api_key"] = "file"
        if model:
            _src["model"] = "explicit"
        elif os.environ.get(ENV_MODEL, ""):
            _src["model"] = "env"
        elif _fc.get("model", ""):
            _src["model"] = "file"
        self._base = (base_url or os.environ.get(ENV_BASE, "")
                      or _fc.get("base_url", "")).strip()
        self._key = (api_key if api_key is not None
                     else (os.environ.get(ENV_KEY, "")
                           or _fc.get("api_key", ""))).strip()
        self._model = (model or os.environ.get(ENV_MODEL, "")
                       or _fc.get("model", "")).strip()
        try:
            # ★★★ R36 修的**优先级 bug**:
            #   docstring 说「显式参数 > 环境变量 > config 文件」
            #   而我实现成了 `env or 文件 or 参数` ⇒ **参数最低**
            #   ⇒⇒ ⇒★ 实测后果: 测试传 timeout=2 想造超时，
            #     却被 config 里的 60 **覆盖** ⇒ 永不超时
            #     ⇒⇒ 连带: 我的重试测试**测不到重试**（断言因此红）
            #   ⇒⇒ ⇒★★ 这是『名字与实现不对齐』（我 R34 刚立的规矩）
            #   ⇒ ⇒★ 修成与 base/key/model **同一口径**
            if timeout is not None:
                self.timeout = float(timeout)
                _src["timeout"] = "explicit"
            elif os.environ.get(ENV_TIMEOUT, ""):
                self.timeout = float(os.environ.get(ENV_TIMEOUT, ""))
                _src["timeout"] = "env"
            elif _fc.get("timeout", ""):
                self.timeout = float(_fc.get("timeout", ""))
                _src["timeout"] = "file"
            else:
                self.timeout = 30.0
                _src["timeout"] = "factory"
        except ValueError:
            self.timeout = float(timeout)
        # ★★★ R377 · 推理预算（与 timeout 同口径: 显式 > env > 文件 > 工厂）
        #   为什么默认从 1600 提到 4096: 实测失败任务推理 5500+ 字，
        #   1600 token 预算被推理吃光 ⇒ content 一个字都没写 ⇒ finish=length。
        #   推理长度不受 max_tokens 约束（端点把 reasoning 计入 total），
        #   所以预算必须留足「推理 + 正文」两部分。
        try:
            if max_tokens is not None:
                self.max_tokens = int(max_tokens)
                _src["max_tokens"] = "explicit"
            elif os.environ.get(ENV_MAX_TOKENS, ""):
                self.max_tokens = int(os.environ.get(ENV_MAX_TOKENS, ""))
                _src["max_tokens"] = "env"
            elif _fc.get("max_tokens", ""):
                self.max_tokens = int(_fc.get("max_tokens", ""))
                _src["max_tokens"] = "file"
            else:
                self.max_tokens = 4096
                _src["max_tokens"] = "factory"
        except (ValueError, TypeError):
            self.max_tokens = 4096
            _src["max_tokens"] = "factory"
        #: ★ 推理强度（`none`/`low`/`minimal`...）。**未配就不发** ——
        #:   不猜端点支持什么（对不支持的端点发无效字段会 400）。
        _re = (reasoning_effort if reasoning_effort is not None
               else (os.environ.get(ENV_REASONING_EFFORT, "")
                     or _fc.get("reasoning_effort", "")))
        self.reasoning_effort = str(_re or "").strip()
        if self.reasoning_effort:
            _src["reasoning_effort"] = (
                "explicit" if reasoning_effort is not None
                else ("env" if os.environ.get(ENV_REASONING_EFFORT, "")
                      else "file"))
        #: ★★ 三态分开（纪律③）: configured 是**静态**的
        self.configured = bool(self._base and self._key and self._model)
        self._probe = probe
        # ★★★ R36 · 重试（**只对传输类错误** —— 不是无脑重试）
        #   实测: e2e 里 LLM 超时一次 ⇒ 整段 step9 就跳过了
        #   ⇒⇒ ⇒★ 而超时通常是**暂时的**（端点抖动）
        #     ⇒ 一次重试能把"白跑 45s"救回来
        #   ⇒⇒ ⇒★ 但**只**对 transport/timeout 重试:
        #     · 4xx（key错/欠费）重试**必然**再失败 ⇒ 浪费
        #     · 解析失败重试也没用（同样的 prompt 大概率同样返回）
        #   ⇒ 配 DWC_LLM_RETRIES 可关（默认 2 次; R265 起 5xx/429
#     网关瞬时类同样重试+退避 — 502 实测曾零韧性判死任务）
        try:
            if os.environ.get("DWC_LLM_RETRIES", ""):
                self.retries = int(os.environ.get("DWC_LLM_RETRIES", ""))
                _src["retries"] = "env"
            else:
                self.retries = 2
                _src["retries"] = "factory"
        except ValueError:
            self.retries = 2
            _src["retries"] = "factory"
        #: ★ R308-③ · 来源审计表（层名集合，不含任何值）。
        self.sources: Dict[str, str] = dict(_src)
        #: 调用账本（可审计: 试了几次、成几次）
        self.n_calls = 0
        self.n_ok = 0
        self.n_fail = 0
        self.n_retries = 0
        #: ★ R439 · 价目表（只读一次；文件缺失 ⇒ {} ⇒ cost_usd=None）
        #:   不在每次调用时读盘：LLM 调用已经是瓶颈，不再加 I/O。
        self._pricing: Dict[str, Any] = cost.load_pricing()

    # ── token 记账（R439 · P0-a）───────────────────────────

    def _attach_usage(self, meta: Dict[str, Any],
                      data: Any = None) -> Dict[str, Any]:
        """把 usage 记进 meta 并落盘（旁路，失败不影响调用）。

        ★ 没有 usage ⇒ meta 里**不出现** usage 键（不是 0）。
        ★ 未知模型 ⇒ 有 usage 但没有 cost_usd。
        """
        u = cost.from_response(data) if data is not None else None
        if u is None:
            return meta
        meta["usage"] = u.as_dict()
        c = cost.cost_usd(self._model, u, self._pricing)
        if c is not None:
            meta["cost_usd"] = c
        cost.record(self._model, u, c)
        return meta

    # ── 凭证护栏（纪律①）─────────────────────────────────

    def __repr__(self) -> str:
        return ("LLMClient(configured=%s, model=%r, timeout=%s, base_host=%r)"
                % (self.configured, self._model, self.timeout,
                   self._host_only()))

    def _host_only(self) -> str:
        """★ 只留 host（端口不含路径）—— 便于排查且**不含 key**。"""
        try:
            from urllib.parse import urlparse
            return urlparse(self._base).netloc or ""
        except Exception:
            return ""

    def __getstate__(self) -> Dict[str, Any]:
        """★ 序列化时**丢掉 key**（否则可能被写进中间产物/缓存）。"""
        st = self.__dict__.copy()
        st["_key"] = ""
        return st

    # ── 可用性（三态）──────────────────────────────────

    @property
    def unavailable_reason(self) -> str:
        """★ 静态不可用的原因（**永远非空** —— 不许返回空字符串）。"""
        if not self._base:
            return ("未配置 %s，也未在 config/llm.json 给 base_url"
                    % ENV_BASE)
        if not self._key:
            return "未配置 %s" % ENV_KEY
        if not self._model:
            return "未配置 %s" % ENV_MODEL
        return ""

    def probe(self) -> LLMResult:
        """★ 动态探活（可选 —— 默认不发网络请求）。

        ★★ 为什么不默认探: 探活本身要花一次调用（时间+配额）
          ⇒ 若每个用到的地方都探，成本会**乘上去**
          ⇒ ⇒★ 交给调用方在需要时显式调
        """
        if not self.configured:
            return LLMResult(ok=False, source="not_configured",
                             error=self.unavailable_reason or "无配置")
        # ★ 修(2026-10-14 实测阶梯): max_tokens=8 时思考型模型(MiMo-V2.6)
        #   的 reasoning 吃光预算 ⇒ content 恒空 ⇒ probe 假报"端点坏"。
        #   阶梯: 8=空 / 64=OK / 512=OK ⇒ 256 留足思考余量。
        return self.complete("ping", max_tokens=256)

    # ── 调用 ──────────────────────────────────────────

    def complete(self, prompt: str, *, system: Optional[str] = None,
                 max_tokens: Optional[int] = None, json_mode: bool = False,
                 images: Optional[List[str]] = None,
                 tools: Optional[List[dict]] = None,
                 tool_choice: Optional[str] = None,
                 _retry: bool = False) -> LLMResult:
        """★ 一次补全。**不抛异常**（纪律②），失败也带 `error` 返回。

        ★★★ 为什么不用异常: 调用方最常见的写法是
          `try: llm.complete(...) except: pass`
          ⇒⇒ 那正是 G7 静默门要防的（我 R29 刚因此被抓过）
        ⇒ ⇒★ 返回值模式让"降级"成为**正常分支**而非异常分支
        """
        if not self.configured:
            return LLMResult(ok=False, source="not_configured",
                             error=self.unavailable_reason or "无配置")

        # ★ R377 · 未显式传 ⇒ 用实例配置（env/文件/工厂），不再写死 1200
        #   ★ getattr 兜底: 旧夹具用 __new__ 绕过 __init__（没有该属性）
        if max_tokens is None:
            max_tokens = getattr(self, "max_tokens", 1200)

        # ★ R226 · 多模态: images=[文件路径] ⇒ OpenAI content 数组形态
        #   （text + image_url data URI）; 端点不支持会 4xx ⇒ 走失败分支
        #   如实报（不假装能看图 — 探测成本高, 让真实调用说话）
        user_content: Any = prompt
        if images:
            import base64
            parts: List[Dict[str, Any]] = [{"type": "text", "text": prompt}]
            for ip in images[:4]:               # 上限 4 图（上下文有界）
                ext = os.path.splitext(str(ip))[1].lower()
                mime = {".png": "image/png", ".jpg": "image/jpeg",
                        ".jpeg": "image/jpeg", ".webp": "image/webp"
                        }.get(ext, "image/png")
                try:
                    b64 = base64.b64encode(
                        open(ip, "rb").read()).decode("ascii")
                    parts.append({"type": "image_url",
                                  "image_url": {"url":
                                      "data:%s;base64,%s" % (mime, b64)}})
                except OSError:
                    continue                    # 单图读失败不炸整体
            if len(parts) > 1:
                user_content = parts
        body: Dict[str, Any] = {
            "model": self._model,
            "messages": ([{"role": "system", "content": system}]
                         if system else [])
            + [{"role": "user", "content": user_content}],
            "max_tokens": max_tokens,
            "temperature": 0.2,   # ★ 低温度: 候选要可复现（便于判分）
        }
        if json_mode:
            body["response_format"] = {"type": "json_object"}
        # ★★★ R384 · 原生 tool calling（不传则不出现该键，老调用方行为不变）
        if tools:
            body["tools"] = tools
            if tool_choice:
                body["tool_choice"] = tool_choice
        # ★ R377 · 推理强度（配了才发；未配不猜端点支持什么）
        if getattr(self, "reasoning_effort", ""):
            body["reasoning_effort"] = self.reasoning_effort

        self.n_calls += 1
        # ★★★ R422 · **每次调用重置重试计数** ——
        #   原实现只在**成功**路径归零（见文末 n_ok 分支），失败后
        #   `_attempts` 停在 2 ⇒ 之后每次调用 `_attempts < retries` 恒假
        #   ⇒ **整个进程只重试第一次**。
        #   现场：2026-10-21 23:41 端点 502，第一单烧完 2 次重试后，
        #   后面 12 单全部零重试、零动作、直接判失败。
        #   ★ 递归重试传 `_retry=True`，否则会无限重置。
        if not _retry:
            self._attempts = 0
        url = self._base.rstrip("/") + "/chat/completions"
        # ★ R267 session: 单实例稳定 id — per-client 家族稳定，
        #   无显式 session ⇒ 生成一个 ephemeral（需求由 OpenCode Go 执行）
        if not getattr(self, "_session_id", None):
            import uuid as _uuid
            self._session_id = "dwc-" + _uuid.uuid4().hex[:16]
        _headers = {
            "Content-Type": "application/json",
            "Authorization": "Bearer " + self._key,
            "User-Agent": "Divine-Wisdom-Core/1.0 (+dwccore)",
            "x-opencode-session": self._session_id,
        }
        req = urllib.request.Request(
            url, data=json.dumps(body).encode("utf-8"),
            headers=_headers,
            method="POST")
        try:
            # ★★★ R379 · 串行化（端点并发下不遵守 json_mode，见 _HTTP_LOCK 注释）
            with _HTTP_LOCK:
                with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                    raw = resp.read().decode("utf-8", "replace")
        except urllib.error.HTTPError as e:
            # ★★★ R265 · 5xx/429 **网关瞬时类**也重试（2026-10-14 用户实测:
            #   "流式失败且回退失败: HTTP 502" 16.2s 任务判死 — 原 R36 只重试
            #   传输异常, HTTPError 分支一发就 return ⇒ 瞬时 502 零韧性）。
            #   判据: 5xx/429=上游瞬时(重试有意义); 4xx=请求错(重试无意义)。
            #   ★★ 只读 e.code/e.reason — 不读 body（可能含 Authorization）。
            if e.code in (429, 500, 502, 503, 504) and self.retries > 0 \
                    and self._attempts < self.retries:
                self.n_retries += 1
                self._attempts += 1
                import time as _t
                _t.sleep(min(0.5 * (2 ** (self._attempts - 1)), 3.0))  # 退避
                return self.complete(prompt, system=system,
                                     max_tokens=max_tokens,
                                     json_mode=json_mode, images=images,
                                     tools=tools, tool_choice=tool_choice,
                                     _retry=True)
            self.n_fail += 1
            return LLMResult(ok=False, source="error",
                             error="HTTP %s: %s" % (e.code, e.reason),
                             meta={"http_code": e.code,
                                   "n_retry_used": self._attempts})
        except Exception as e:      # ★ 网络/超时 —— 统一收敛
            # ★★★ R36: **传输类**错误才重试（见 __init__ 的理由）
            if self.retries > 0 and self._attempts < self.retries:
                self.n_retries += 1
                self._attempts += 1
                import time as _t
                _t.sleep(min(0.5 * (2 ** (self._attempts - 1)), 3.0))  # 退避
                return self.complete(prompt, system=system,
                                     max_tokens=max_tokens,
                                     json_mode=json_mode, images=images,
                                     tools=tools, tool_choice=tool_choice,
                                     _retry=True)
            self.n_fail += 1
            return LLMResult(ok=False, source="error",
                             error="%s: %s" % (type(e).__name__, e),
                             meta={"kind": "transport",
                                   "n_retry_used": self._attempts})
        try:
            data = json.loads(raw)
            # ★★★ R376 · 推理模型的 `content` 空**不是**「可以拿 reasoning
            #   顶替答案」的信号 —— 那是 max_tokens 被推理吃光（实测
            #   max_tokens=300 ⇒ content_len=0 / finish_reason="length"）。
            #   旧代码用 reasoning_content 顶替并返回 ok=True ⇒ 下游
            #   `_extract_json` 拿到英文推理散文 ⇒ 报「响应非 JSON」⇒
            #   用户看到「任务未完成」，而真正的失败原因（token 耗尽）
            #   被彻底掩盖。**降级与成功必须可区分**（本项目纪律）。
            msg = data["choices"][0]["message"]
            ch0 = data["choices"][0]
            finish = ch0.get("finish_reason")
            text = msg.get("content")
            # ★★★ R384 · 原生 tool_calls —— 端点返回 tool_calls 时
            #   `content` 是**空串**。旧代码下面 `if not text.strip()`
            #   直接判 kind="empty" ⇒ **tool_calls 被当成空响应丢弃**，
            #   这是「94% 零动作」的致命一环（模型想调工具也没用）。
            _tool_calls = msg.get("tool_calls") or []
            # R327 兼容: opencode/MiMo 用 `reasoning` 键名。两键都认，
            # 但**只用于诊断**，绝不顶替正文。
            rc = msg.get("reasoning_content") or msg.get("reasoning") or ""
        except Exception as e:
            self.n_fail += 1
            return LLMResult(ok=False, source="error",
                             error="响应解析失败: %s" % e,
                             meta={"kind": "parse"})
        if not isinstance(text, str) or not text.strip():
            # ★★★ R384 · 有 tool_calls ⇒ 这不是空响应，是「模型要调工具」。
            #   必须在"空内容判死"**之前**拦下（否则 tool_calls 被丢弃）。
            if _tool_calls:
                self.n_ok += 1
                self._attempts = 0
                return LLMResult(ok=True, text="", source="llm",
                                 meta=self._attach_usage(
                                     {"model": self._model,
                                      "tool_calls": _tool_calls,
                                      "finish_reason": finish,
                                      "content_chars": 0}, data))
            self.n_fail += 1
            if isinstance(rc, str) and rc.strip():
                # 推理吃光 token ⇒ 如实报「只有推理，没有正文」，不冒充答案
                return LLMResult(
                    ok=False, source="error",
                    error=("模型只产出推理、没有正文（finish_reason=%s，"
                           "推理 %d 字）— 多半是 max_tokens 被推理吃光，"
                           "请调大 max_tokens 或换非推理模型"
                           % (finish, len(rc))),
                    meta={"kind": "reasoning_only",
                          "finish_reason": finish,
                          "reasoning_chars": len(rc),
                          "content_chars": 0})
            return LLMResult(ok=False, source="error",
                             error="返回内容为空（不许静默当成功）",
                             meta={"kind": "empty", "finish_reason": finish})
        self.n_ok += 1
        self._attempts = 0      # ★ 成功后归零（下次调用从头数）
        return LLMResult(ok=True, text=text, source="llm",
                         meta=self._attach_usage(
                             {"model": self._model,   # ★ model 名可记
                              "n_chars": len(text),
                              "finish_reason": finish}, data))

    def complete_stream(self, prompt: str, *, system=None,
                        max_tokens: Optional[int] = None, json_mode: bool = False,
                        images=None, on_delta=None) -> LLMResult:
        """★ token 级流式补全（R237）: SSE 逐 delta 回调 on_delta(text)。

        ★ 与 complete 同契约: 返回 LLMResult, 不抛; 失败如实报。
        ★ 回退链（诚实）: 流式请求失败（端点不支持/非 SSE）⇒ 自动回退
          complete() 整段, meta.stream_fallback=True（用不用流看得见）。
        ★ on_delta 是**增量原文**回调 — 由调用方决定怎么渲染。"""
        if not self.configured:
            return LLMResult(ok=False, source="not_configured",
                             error=self.unavailable_reason or "无配置")
        import copy as _copy
        # ★ R377 · 未显式传 ⇒ 用实例配置（与 complete 同口径）
        if max_tokens is None:
            max_tokens = getattr(self, "max_tokens", 1200)
        # 复用 complete 的 body 构造 — 从一次完整请求拷一份（避免双实现漂移）
        # 快法: 先打一个不读流的探测——直接构造同款请求加 stream:True
        user_content: Any = prompt
        if images:
            import base64
            parts: List[Dict[str, Any]] = [{"type": "text", "text": prompt}]
            for ip in images[:4]:
                ext = os.path.splitext(str(ip))[1].lower()
                mime = {".png": "image/png", ".jpg": "image/jpeg",
                        ".jpeg": "image/jpeg", ".webp": "image/webp"
                        }.get(ext, "image/png")
                try:
                    b64 = base64.b64encode(
                        open(ip, "rb").read()).decode("ascii")
                    parts.append({"type": "image_url",
                                  "image_url": {"url":
                                      "data:%s;base64,%s" % (mime, b64)}})
                except OSError:
                    continue
            if len(parts) > 1:
                user_content = parts
        body: Dict[str, Any] = {
            "model": self._model,
            "messages": ([{"role": "system", "content": system}]
                         if system else [])
            + [{"role": "user", "content": user_content}],
            "max_tokens": max_tokens,
            "temperature": 0.2,
            "stream": True,
        }
        if json_mode:
            body["response_format"] = {"type": "json_object"}
        # ★ R377 · 推理强度（与 complete 同口径）
        if getattr(self, "reasoning_effort", ""):
            body["reasoning_effort"] = self.reasoning_effort
        self.n_calls += 1
        url = self._base.rstrip("/") + "/chat/completions"
        if not getattr(self, "_session_id", None):
            import uuid as _uuid
            self._session_id = "dwc-" + _uuid.uuid4().hex[:16]
        req = urllib.request.Request(
            url, data=json.dumps(body).encode("utf-8"),
            headers={"Content-Type": "application/json",
                     "Authorization": "Bearer " + self._key,
                     "User-Agent": "Divine-Wisdom-Core/1.0 (+dwccore)",
                     "x-opencode-session": self._session_id},
            method="POST")
        chunks: List[str] = []
        rc_chunks: List[str] = []
        finish = [None]
        try:
            # ★★★ R379 · 串行化（流式同样 —— 生产 progress 路径走这里）
            with _HTTP_LOCK:
                with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                    ctype = (resp.headers.get("Content-Type") or "").lower()
                    if ("event-stream" not in ctype
                            and "text/plain" not in ctype):
                        raise ValueError("非 SSE 响应: %s" % ctype[:60])
                    for raw in resp:
                        line = raw.decode("utf-8", "replace").strip()
                        if not line.startswith("data:"):
                            continue
                        payload = line[5:].strip()
                        if payload == "[DONE]":
                            break
                        try:
                            ch = json.loads(payload)["choices"][0]
                            delta = ch.get("delta", {}) or {}
                            if ch.get("finish_reason"):
                                finish[0] = ch["finish_reason"]
                        except (ValueError, KeyError, IndexError):
                            continue                # 单帧坏不炸流
                        # ★★★ R376 · 推理 delta 绝不拼进正文 —— 旧代码
                        #   `if not piece: piece = delta.get("reasoning_content")`
                        #   把推理当正文推给 on_delta，下游拼出的 text 是英文
                        #   散文（用户看到「任务未完成」的真因）。
                        piece = delta.get("content")
                        if not piece:
                            rc_piece = (delta.get("reasoning_content")
                                        or delta.get("reasoning"))
                            if rc_piece:
                                rc_chunks.append(rc_piece)
                            continue
                        chunks.append(piece)
                        if on_delta:
                            on_delta(piece)
            text = "".join(chunks)
            reasoning = "".join(rc_chunks)
        except Exception as e:                  # noqa: BLE001 — 流失败回退整段
            if self.retries > 0 and getattr(self, "_stream_fb", False) is False:
                self._stream_fb = True
            self.n_fail += 1
            fb = self.complete(prompt, system=system, max_tokens=max_tokens,
                               json_mode=json_mode, images=images)
            if fb.ok:
                self.n_ok += 1                  # 回退成功计入（账本仍如实）
                return LLMResult(ok=True, text=fb.text, source="llm",
                                 meta=dict(
                                     {"stream_fallback": True,
                                      "fallback_reason": "%s: %s"
                                      % (type(e).__name__, str(e)[:80]),
                                      "n_chars": len(fb.text)},
                                     # ★ R439 · 回退的那次已经记过账，这里只搬运，不重复记
                                     **{k: v for k, v in fb.meta.items()
                                        if k in ("usage", "cost_usd")}))
            return LLMResult(ok=False, source="error",
                             error="流式失败且回退失败: %s" % fb.error[:120],
                             meta={"stream_error": str(e)[:80]})
        finally:
            self._stream_fb = False
        if not text.strip():
            self.n_fail += 1
            if reasoning.strip():
                # ★ R376 · 只有推理没有正文 ⇒ 如实报，不冒充答案
                return LLMResult(
                    ok=False, source="error",
                    error=("模型只产出推理、没有正文（finish_reason=%s，"
                           "推理 %d 字）— 多半是 max_tokens 被推理吃光，"
                           "请调大 max_tokens 或换非推理模型"
                           % (finish[0], len(reasoning))),
                    meta={"kind": "reasoning_only",
                          "finish_reason": finish[0],
                          "reasoning_chars": len(reasoning),
                          "content_chars": 0,
                          "streamed": True})
            return LLMResult(ok=False, source="error",
                             error="流式返回内容为空",
                             meta={"kind": "empty", "finish_reason": finish[0]})
        self.n_ok += 1
        return LLMResult(ok=True, text=text, source="llm",
                         meta={"model": self._model, "streamed": True,
                               "n_chars": len(text),
                               "n_chunks": len(chunks),
                               "finish_reason": finish[0]})

    def stats(self) -> Dict[str, Any]:
        """★ 调用账本（不含量任何凭证）。"""
        return {"configured": self.configured, "model": self._model,
                "n_calls": self.n_calls, "n_ok": self.n_ok,
                "n_fail": self.n_fail, "n_retries": self.n_retries,
                "retries": self.retries,
                "★": "凭证不在此处任何字段里（纪律①）"}
